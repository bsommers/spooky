import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { describe, expect, it } from 'vitest';
import { UI_ROOT } from '../helpers/themes';

describe('generated API types', () => {
  it('schema.d.ts is exactly what openapi-typescript makes of the committed openapi.json (drift fails)', async () => {
    const doc = JSON.parse(readFileSync(join(UI_ROOT, 'src/api/openapi.json'), 'utf8'));
    const header = '// GENERATED by `npm run gen:api` from the operations registry. Do not edit; `node scripts/gen-api.mjs --check` fails on drift.\n';
    expect(readFileSync(join(UI_ROOT, 'src/api/schema.d.ts'), 'utf8')).toBe(header + astToString(await openapiTS(doc)));
  });

  it('the document is the one the server publishes: every /api path the client can call exists, and none is secured by an API key', () => {
    const doc = JSON.parse(readFileSync(join(UI_ROOT, 'src/api/openapi.json'), 'utf8')) as { paths: Record<string, unknown>; components: Record<string, unknown> };
    expect(Object.keys(doc.paths)).toEqual(expect.arrayContaining(['/api/capabilities', '/api/authors', '/api/generate', '/openapi.json']));
    expect(JSON.stringify(doc.components)).not.toMatch(/"type":\s*"apiKey"/); // a bearer token at most; provider keys never reach the UI
  });
});
