// Regenerates the typed API surface from the server's own OpenAPI document.
//
//   node scripts/gen-api.mjs           write src/api/openapi.json and src/api/schema.d.ts
//   node scripts/gen-api.mjs --check   exit 1 if either committed file differs from what the registry generates now
//
// The document comes from the compiled operations registry (`npm run build` at the repo root), the same code that serves
// GET /openapi.json, so the client types cannot drift from the server without this check failing.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = resolve(here, '..', 'src', 'api');
const check = process.argv.includes('--check');

const { buildOpenApi, serializeOpenApi } = await import(pathToFileURL(resolve(here, '..', '..', 'dist', 'src', 'service', 'openapi.js')).href);
const json = serializeOpenApi(buildOpenApi({ version: '0.0.0' }));
const ast = await openapiTS(JSON.parse(json));
const header = '// GENERATED by `npm run gen:api` from the operations registry. Do not edit; `node scripts/gen-api.mjs --check` fails on drift.\n';
const dts = header + astToString(ast);

const targets = [
  [resolve(apiDir, 'openapi.json'), json.endsWith('\n') ? json : json + '\n'],
  [resolve(apiDir, 'schema.d.ts'), dts],
];
let drift = false;
for (const [file, want] of targets) {
  let have = '';
  try {
    have = readFileSync(file, 'utf8');
  } catch {
    /* missing counts as drift */
  }
  if (have === want) continue;
  if (check) {
    console.error(`gen-api: ${file} is out of date; run "npm run gen:api" in ui/`);
    drift = true;
  } else {
    writeFileSync(file, want);
    console.log(`gen-api: wrote ${file}`);
  }
}
process.exit(drift ? 1 : 0);
